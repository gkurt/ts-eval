// Compares tsc (TypeScript 7) and `bun check` on ts-eval workloads.
//
// usage: node bench/checkers.cjs [--runs N] [--out FILE]
//
// Each case is checked by both, several times; the table shows the median wall
// time (process start to exit, so it includes startup), whether the check
// passed, and the instantiation count tsc reports. A single `Eval` is one
// declaration, so its cost cannot be spread over threads: those rows compare
// raw single-thread speed and per-declaration budgets. The suite rows can use
// every core.
const { spawnSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const root = path.resolve(__dirname, '..');
const arg = (name, dflt) => {
  const i = process.argv.indexOf(name);
  return i < 0 ? dflt : process.argv[i + 1];
};
const runs = +arg('--runs', 3);
const out = arg('--out', path.join(__dirname, 'RESULTS.md'));

const tscJs = path.join(root, 'node_modules/typescript/bin/tsc');
const bunExe = path.join(root, 'node_modules/bun/bin', process.platform === 'win32' ? 'bun.exe' : 'bun');
const caseFile = path.join(__dirname, 'case.ts');

const checkers = {
  tsc: (project, extra = []) => [process.execPath, [tscJs, '-p', project, '--pretty', 'false', ...extra]],
  bun: (project) => [bunExe, ['check', '-p', project, '--no-pretty']],
};

const fib = 'function fib(n) { return n < 2 ? n : fib(n - 1) + fib(n - 2) }';
const loop = 'function(n) { let s = 0; for (let i = 0; i < n; i++) s += i; return s }';
const fibOf = (n) => (n < 2 ? n : fibOf(n - 1) + fibOf(n - 2));
const single = (label, src, arg, expected) => ({ label, project: 'bench', file: `import type { Eval } from '../src/index';
export const result: ${expected} = null! as Eval<'${src}', ${arg}>;
` });

const cases = [
  { label: 'Test suite (`npm test`)', project: '.' },
  { label: 'Examples (`npm run examples`)', project: 'examples' },
  single('`(a, b) => a + b` (baseline)', '(a, b) => a + b', '5, 3', 8),
  ...[10, 12, 14, 15].map((n) => single(`\`fib(${n})\``, fib, n, fibOf(n))),
  ...[250, 500, 1000, 2000].map((n) => single(`\`for\` loop, ${n} iterations`, loop, n, (n * (n - 1)) / 2)),
];

function run(cmd, args) {
  const t = process.hrtime.bigint();
  const r = spawnSync(cmd, args, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 26 });
  const ms = Number(process.hrtime.bigint() - t) / 1e6;
  const text = (r.stdout || '') + (r.stderr || '');
  const err = text.match(/error (TS\d+)/);
  return { ms, text, status: !err && r.status === 0 ? 'pass' : err ? err[1] : `exit ${r.status}` };
}

const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];
const fmt = (ms) => (ms >= 1000 ? `${(ms / 1000).toFixed(2)} s` : `${Math.round(ms)} ms`);
const status = (s) => (s === 'pass' ? '' : s === 'TS2589' ? ' ✗ budget' : ` ✗ ${s}`);
const version = (cmd, args) => spawnSync(cmd, args, { encoding: 'utf8' }).stdout.trim();

const rows = [];
try {
  for (const c of cases) {
    if (c.file) fs.writeFileSync(caseFile, c.file);
    const [tc, ta] = checkers.tsc(c.project, ['--extendedDiagnostics']);
    const diag = run(tc, ta);
    const inst = +(diag.text.match(/Instantiations:\s+(\d+)/) || [])[1];
    const res = {};
    for (const [name, make] of Object.entries(checkers)) {
      const results = Array.from({ length: runs }, () => run(...make(c.project)));
      res[name] = { ms: median(results.map((r) => r.ms)), status: results[0].status };
    }
    const speedup = res.tsc.status === 'pass' && res.bun.status === 'pass' ? `${(res.tsc.ms / res.bun.ms).toFixed(1)}×` : '–';
    const row = `| ${c.label} | ${inst ? (inst / 1e6).toFixed(2) + 'M' : '–'} | ${fmt(res.tsc.ms)}${status(res.tsc.status)} | ${fmt(res.bun.ms)}${status(res.bun.status)} | ${speedup} |`;
    console.log(row);
    rows.push(row);
  }
} finally {
  fs.rmSync(caseFile, { force: true });
}

const cpus = os.cpus();
const report = `# Checker benchmarks

Generated by \`npm run bench\` (median of ${runs} runs, wall time including process startup).

- ${cpus[0].model.trim()}, ${cpus.length} threads, ${os.type()} ${os.release()}
- tsc ${version(process.execPath, [tscJs, '--version']).replace(/^Version /, '')}, bun ${version(bunExe, ['--version'])} (npm \`bun@${require(path.join(root, 'node_modules/bun/package.json')).version}\`)

| Case | Instantiations (tsc) | tsc | bun check | Speedup |
|---|---|---|---|---|
${rows.join('\n')}

"✗ budget" is error TS2589: the declaration ran out of its instantiation budget.
`;
fs.writeFileSync(out, report);
console.log(`\nwrote ${path.relative(root, out)}`);
