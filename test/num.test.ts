import type { NAdd, NSub, NMul, NDiv, NMod, NCmp, NPow, NSqrt, Canon, NFloor, NRound, NCeil, NBitOp, NBitNot, NToFixed, NumLit } from '../src/num';
import type { Expect, Equal } from './helpers';

export type NumTests = [
  Expect<Equal<NAdd<'999', '1'>, '1000'>>,
  Expect<Equal<NAdd<'-5', '3'>, '-2'>>,
  Expect<Equal<NAdd<'0.1', '0.2'>, '0.3'>>,
  Expect<Equal<NAdd<'-1.5', '1.5'>, '0'>>,
  Expect<Equal<NSub<'3', '10'>, '-7'>>,
  Expect<Equal<NMul<'123456789', '987654321'>, '121932631112635269'>>,
  Expect<Equal<NMul<'-2.5', '4'>, '-10'>>,
  Expect<Equal<NDiv<'7', '2'>, '3.5'>>,
  Expect<Equal<NDiv<'1', '3'>, '0.3333333333333333'>>,
  Expect<Equal<NDiv<'-10', '4'>, '-2.5'>>,
  Expect<Equal<NDiv<'1', '0'>, 'Infinity'>>,
  Expect<Equal<NMod<'-7', '3'>, '-1'>>,
  Expect<Equal<NMod<'7.5', '2'>, '1.5'>>,
  Expect<Equal<NCmp<'-3', '2'>, -1>>,
  Expect<Equal<NCmp<'10', '9.99'>, 1>>,
  Expect<Equal<NPow<'2', '64'>, '18446744073709551616'>>,
  Expect<Equal<NPow<'2', '-2'>, '0.25'>>,
  Expect<Equal<NSqrt<'144'>, '12'>>,
  Expect<Equal<NSqrt<'2'>, '1.414213562373095'>>,
  Expect<Equal<Canon<'007.50'>, '7.5'>>,
  Expect<Equal<Canon<'1e21'>, '1000000000000000000000'>>,
  Expect<Equal<Canon<'2.5e-3'>, '0.0025'>>,
  Expect<Equal<Canon<'abc'>, 'NaN'>>,
  Expect<Equal<NFloor<'-2.5'>, '-3'>>,
  Expect<Equal<NCeil<'2.1'>, '3'>>,
  Expect<Equal<NRound<'2.5'>, '3'>>,
  Expect<Equal<NRound<'-2.5'>, '-2'>>,
  Expect<Equal<NBitOp<'&', '12', '10'>, '8'>>,
  Expect<Equal<NBitOp<'|', '12', '10'>, '14'>>,
  Expect<Equal<NBitOp<'^', '12', '10'>, '6'>>,
  Expect<Equal<NBitOp<'<<', '1', '31'>, '-2147483648'>>,
  Expect<Equal<NBitOp<'>>', '-16', '2'>, '-4'>>,
  Expect<Equal<NBitOp<'>>>', '-1', '28'>, '15'>>,
  Expect<Equal<NBitNot<'5'>, '-6'>>,
  Expect<Equal<NToFixed<'3.14159', 2>, '3.14'>>,
  Expect<Equal<NToFixed<'2', 3>, '2.000'>>,
  Expect<Equal<NumLit<'-42.5'>, -42.5>>,
  Expect<Equal<NumLit<'123456789012345678901234567890'>, 123456789012345678901234567890n>>,
];
